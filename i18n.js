  const STORE_KEY = 'alpha.lang';
  let current = 'en';

  function pack(code) { return STRINGS[code] || STRINGS.en; }

  function t(key, vars) {
    let s = pack(current)[key];
    if (s === undefined) s = STRINGS.en[key];
    if (s === undefined) return key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(vars[k]);
      });
    }
    return s;
  }

  function detect() {
    let saved = null;
    try { saved = localStorage.getItem(STORE_KEY); } catch (e) { /* blocked */ }
    if (saved && STRINGS[saved]) return saved;

    const nav = (navigator.languages && navigator.languages.length)
      ? navigator.languages : [navigator.language || 'en'];
    for (let i = 0; i < nav.length; i++) {
      const base = String(nav[i]).toLowerCase().split('-')[0];
      if (STRINGS[base]) return base;
    }
    return 'en';
  }

  function apply(root) {
    const scope = root || document;

    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });

    // data-i18n-attr="placeholder:search.placeholder;aria-label:search.clear"
    scope.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        const bits = pair.split(':');
        if (bits.length === 2) el.setAttribute(bits[0].trim(), t(bits[1].trim()));
      });
    });
  }

  function set(code) {
    if (!STRINGS[code]) code = 'en';
    current = code;

    const meta = LANGS.filter(function (l) { return l.code === code; })[0] || LANGS[0];
    document.documentElement.setAttribute('lang', code);
    document.documentElement.setAttribute('dir', meta.dir);

    try { localStorage.setItem(STORE_KEY, code); } catch (e) { /* blocked */ }

    apply();
    document.dispatchEvent(new CustomEvent('alpha:langchange', { detail: { code: code } }));
  }

  window.AlphaI18n = {
    langs: LANGS,
    t: t,
    apply: apply,
    set: set,
    get current() { return current; },
    init: function () { set(detect()); }
  };
